def verification_state():
    """Return a non-degenerate three-dimensional constitutive state."""

    F = np.array(
        [
            [1.08, 0.04, 0.02],
            [0.01, 1.03, 0.03],
            [0.02, 0.01, 1.05],
        ]
    )
    return dict(
        F=F,
        F_old=0.99 * F,
        p=2.0,
        p_old=1.8,
        mu=-900.0,
        grad_mu=np.array([2.0, -1.0, 0.5]),
        dt=0.1,
    )


def generate_source(output_dir: Optional[str] = None) -> Path:
    """Verify the declaration and emit the current CoupFE Abaqus UEL."""

    problem = PressureGelLocalPressureHex8()
    if not problem.verify(state=verification_state(), verbose=False):
        raise RuntimeError("pressure-gel material verification failed")

    out_dir = Path(output_dir) if output_dir else Path(__file__).resolve().parent
    out_dir.mkdir(parents=True, exist_ok=True)
    for_path = out_dir / "pressuregel_local_pressure_hex8.for"
    generate_uel(
        problem,
        str(for_path),
        element="Hex8",
        formulation="local_pressure",
        mat_prefix="pressuregel",
    )
    source = for_path.read_text()
    header_end = "C======================================================================\n"
    if _GENERATED_PROVENANCE not in source:
        source = source.replace(
            header_end, header_end + _GENERATED_PROVENANCE, 1
        )
        for_path.write_text(source)
    return for_path


if __name__ == "__main__":
    print(f"Generated {generate_source()}")
