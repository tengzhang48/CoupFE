from __future__ import annotations

from pathlib import Path
from typing import Optional

import numpy as np

import coupfe.codegen as au
from coupfe.codegen.core.tensor import det, exp, inv, log
from coupfe.codegen.generators.uel_gen import generate_uel


class PressureGelMaterial(au.Material):
    """Pressure-coupled gel: network elasticity and Flory-Huggins mixing."""

    props = dict(
        G=1.0,
        K=100.0,
        chi=0.1,
        D=5.0e-9,
        mu0=0.0,
        Omega=1.0e-4,
        Rgas=8.314,
        theta=298.0,
        phi0=0.5,
    )

    def stress_PK1(self, F, p, mu):
        return self.G * (F - inv(F).T) + p * inv(F).T

    def pressure_resid(self, F, p, mu):
        J = det(F)
        Je = exp(p / self.K)
        phi = self.phi0 * Je / J
        return (
            mu
            - self.mu0
            - self.Rgas
            * self.theta
            * (log(1.0 - phi) + phi + self.chi * phi**2)
            + (phi / self.phi0) * self.Omega * p
        )

    def solvent_flux(self, F, p, mu, grad_mu):
        J = det(F)
        Je = exp(p / self.K)
        phi = self.phi0 * Je / J
        Cinv = inv(F.T @ F)
        cR0 = (1.0 - self.phi0) / self.Omega
        cR = cR0 + (self.phi0 - phi) / (self.Omega * phi)
        mobility = self.D * cR / (self.Rgas * self.theta)
        return -mobility * (Cinv @ grad_mu)

    def solvent_storage(self, F, F_old, p, p_old, dt):
        J = det(F)
        J_old = det(F_old)
        Je = exp(p / self.K)
        Je_old = exp(p_old / self.K)
        return (J / Je - J_old / Je_old) / (self.Omega * dt)


class PressureGelLocalPressureHex8(au.WeakForm):
    """Hex8 with global displacement/chemical potential and local pressure."""

    material = PressureGelMaterial
    ndim = 3

    def define_fields(self):
        self.u = au.VectorField("u", degree=1)
        self.mu = au.ScalarField("mu", degree=1)
        self.p = au.LocalScalar(
            "p", storage="SVARS", condensed=True, initial=0.0
        )

    def momentum_equation(self, v, F, p, mu):
        return self.material.stress_PK1(F, p, mu)

    def pressure_equation(self, q, F, p, mu):
        return self.material.pressure_resid(F, p, mu)

    def transport_equation(
        self, w, F, p, mu, grad_mu, F_old, p_old, dt
    ):
        c_dot = self.material.solvent_storage(F, F_old, p, p_old, dt)
        j_R = self.material.solvent_flux(F, p, mu, grad_mu)
        return c_dot, j_R


