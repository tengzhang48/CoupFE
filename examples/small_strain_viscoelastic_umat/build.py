"""Generate a small-strain Standard Linear Solid UMAT."""

from __future__ import annotations

import math
from pathlib import Path
import sys

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

import coupfe.codegen as au
from coupfe.codegen.core.tensor import eye, trace


class SmallStrainViscoelastic(au.SmallStrainMaterial):
    """Compression-positive SLS with one deviatoric Maxwell branch.

    ``PROPS`` order is ``K, G_inf, G_v, tau``. The viscous strain tensor
    ``eps_v`` occupies ``STATEV(1..9)`` in column-major order.
    """

    props = dict(K=30.0, G_inf=10.0, G_v=5.0, tau=0.5)
    state_vars = dict(eps_v=np.zeros((3, 3)))

    def stress_update(self, sigma_old, strain_old, dstrain, eps_v_old, dt):
        I = eye(3)
        strain_new = strain_old + dstrain
        ratio = dt / self.tau

        dev_e = strain_new - (1.0 / 3.0) * trace(strain_new) * I
        eps_v_new = (eps_v_old + ratio * dev_e) / (1.0 + ratio)
        sigma_new = (
            self.K * trace(strain_new) * I
            + 2.0 * self.G_inf * dev_e
            + 2.0 * self.G_v * (dev_e - eps_v_new)
        )
        return sigma_new, {"eps_v": eps_v_new}


STEP_TENSOR_SHEAR = 0.01
TIME_INCREMENT = 0.1
N_INCREMENTS = 30

