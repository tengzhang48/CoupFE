def test_generate_and_object_compile(tmp_path):
    ex = _load_example()
    for_path = ex.generate_source(str(tmp_path))

    source = for_path.read_text()
    retained_source = (
        _EXAMPLE_DIR / "pressuregel_local_pressure_hex8.for"
    ).read_text()
    assert source == retained_source
    assert "Generated by coupfe.codegen" in source
    assert "Original declaration Copyright (c) 2026 Teng Zhang, MIT." in source
    assert "Element: Hex8, NDOFEL = 32" in source
    assert "SUBROUTINE UEL" in source

    compiler = shutil.which("gfortran")
    if compiler is None:
        pytest.skip("gfortran not available")

    result = subprocess.run(
        [
            compiler,
            "-c",
            "-ffixed-form",
            "-ffixed-line-length-none",
            str(for_path),
        ],
        cwd=tmp_path,
        capture_output=True,
        text=True,
        check=False,
    )
    assert result.returncode == 0, result.stderr
    assert (tmp_path / "pressuregel_local_pressure_hex8.o").is_file()


