C
      IMPLICIT NONE
      INTEGER, INTENT(IN) :: iface
      DOUBLE PRECISION, INTENT(IN)  :: s1, s2
      DOUBLE PRECISION, INTENT(OUT) :: N_face(8), dNds(8,2)
      INTEGER, INTENT(OUT) :: n_face_nodes

      DOUBLE PRECISION :: sp1, sm1, sp2, sm2
      DOUBLE PRECISION :: s1sq, s2sq

