      SUBROUTINE neohookean_cs_tangent_dPdF(
     &  F, PROPS, dPdF)
      IMPLICIT NONE
      DOUBLE PRECISION, INTENT(IN) :: F(3,3)
      DOUBLE PRECISION, INTENT(IN) :: PROPS(2)
      DOUBLE PRECISION, INTENT(OUT) :: dPdF(3,3,3,3)

C     CS_H = 1e-10: verified for this framework
      DOUBLE PRECISION, PARAMETER :: CS_H = 1.0d-10
      DOUBLE COMPLEX :: Fz(3,3), Pz(3,3)
      INTEGER :: i, j, k, l

      DO k = 1, 3
        DO l = 1, 3
          CALL real2complex33(F, Fz)
          Fz(k,l) = Fz(k,l)
     &      + DCMPLX(0.0d0, CS_H)
          CALL neohookean_stress_PK1(
     &      Fz, PROPS, Pz)
          DO i = 1, 3
            DO j = 1, 3
              dPdF(i,j,k,l) =
     &          AIMAG(Pz(i,j)) / CS_H
            END DO
          END DO
        END DO
      END DO

      RETURN
      END SUBROUTINE neohookean_cs_tangent_dPdF

