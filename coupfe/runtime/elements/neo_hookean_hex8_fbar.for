C     Section 2: Material subroutines (COMPLEX*16)
C     AST-translated from Python Material methods
C======================================================================
      SUBROUTINE neohookean_stress_PK1(F, props, P_out)
      IMPLICIT NONE
      DOUBLE COMPLEX, INTENT(IN) :: F(3,3)
      DOUBLE PRECISION, INTENT(IN) :: props(2)
      DOUBLE COMPLEX, INTENT(OUT) :: P_out(3,3)

      DOUBLE COMPLEX :: det33z
      DOUBLE COMPLEX :: INV1(3,3)
      DOUBLE COMPLEX :: AT2(3,3)
      DOUBLE COMPLEX :: FinvT(3,3)
      DOUBLE COMPLEX :: J
      INTEGER :: ii, jj

      J = det33z(F)
      CALL inv33z(F, INV1)
      CALL transpose33z(INV1, AT2)
      FinvT = AT2

      DO ii = 1, 3
        DO jj = 1, 3
          P_out(ii,jj) = ((DCMPLX(props(1), 0.0d0) * (F(ii,jj) -
     &FinvT(ii,jj))) + ((DCMPLX(props(2), 0.0d0) * LOG(J)) * FinvT(ii,
     &jj)))
        END DO
      END DO

      RETURN
      END SUBROUTINE neohookean_stress_PK1


